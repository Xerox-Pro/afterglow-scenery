"""Package the buildless site as a self-contained Cloudflare Worker."""
from pathlib import Path
import base64, gzip, hashlib, json

root = Path(__file__).resolve().parent
assets = {}
types = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.txt': 'text/plain; charset=utf-8'}
for path in sorted((root / 'dist').iterdir()):
    if path.is_file():
        raw = path.read_bytes()
        assets['/' + path.name] = {'data': base64.b64encode(gzip.compress(raw, compresslevel=9, mtime=0)).decode(), 'type': types.get(path.suffix, 'application/octet-stream'), 'etag': hashlib.sha256(raw).hexdigest()[:20]}
assets['/THREE-LICENSE.txt'] = {'data': base64.b64encode(gzip.compress((root / 'THREE-LICENSE.txt').read_bytes(), mtime=0)).decode(), 'type': types['.txt'], 'etag': 'three-mit-license'}
worker = '''// Generated by build.py. Static, original assets only; no credentials.
const ASSETS = __ASSETS__;
export default {
  fetch(request) {
    const url = new URL(request.url);
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', {status:405,headers:{Allow:'GET, HEAD'}});
    if (url.pathname === '/health') return Response.json({ok:true,site:'AFTERGLOW',scenes:4});
    const key = url.pathname === '/' ? '/index.html' : url.pathname;
    const asset = ASSETS[key];
    if (!asset) return new Response('Not found', {status:404,headers:{'Content-Type':'text/plain; charset=utf-8'}});
    const headers = {'Content-Type':asset.type, 'Content-Encoding':'gzip', 'ETag':'"'+asset.etag+'"', 'Cache-Control':'public, max-age=0, must-revalidate', 'X-Content-Type-Options':'nosniff', 'Referrer-Policy':'strict-origin-when-cross-origin', 'Permissions-Policy':'camera=(), microphone=(), geolocation=()'};
    if(request.headers.get('If-None-Match') === headers.ETag) return new Response(null,{status:304,headers});
    const bytes = request.method === 'HEAD' ? null : Uint8Array.from(atob(asset.data), c => c.charCodeAt(0));
    return new Response(bytes, {headers, encodeBody:'manual'});
  }
};
'''.replace('__ASSETS__', json.dumps(assets, ensure_ascii=False, separators=(',', ':')))
(root / 'worker.mjs').write_text(worker)
print(f'Packaged {len(assets)} assets, worker {len(worker.encode())} bytes')
